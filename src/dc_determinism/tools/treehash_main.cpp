// Build-time helper: dc_determinism_treehash --tree DIR [--emit-cpp FILE]
// Prints the LF-normalised tree hash of DIR; with --emit-cpp it also
// writes the generated source that embeds the hash as dc_determinism::kSourceTreeSha256.
#include <cstdio>
#include <fstream>
#include <string>

#include "common/error.hpp"
#include "common/platform.hpp"
#include "common/tree_hash.hpp"

int main(int argc, char** argv) {
    using namespace dc_determinism;
    std::string tree;
    std::string emit;
    std::vector<std::string> args = utf8_arguments(argc, argv);
    for (std::size_t i = 1; i < args.size(); ++i) {
        if (args[i] == "--tree" && i + 1 < args.size()) {
            tree = args[++i];
        } else if (args[i] == "--emit-cpp" && i + 1 < args.size()) {
            emit = args[++i];
        } else {
            std::fprintf(stderr, "usage: dc_determinism_treehash --tree DIR [--emit-cpp FILE]\n");
            return 2;
        }
    }
    if (tree.empty()) {
        std::fprintf(stderr, "usage: dc_determinism_treehash --tree DIR [--emit-cpp FILE]\n");
        return 2;
    }
    try {
        std::string digest = tree_sha256_lf(path_from_utf8(tree));
        std::printf("%s\n", digest.c_str());
        if (!emit.empty()) {
            std::ofstream out(path_from_utf8(emit), std::ios::binary | std::ios::trunc);
            out << "// Generated by dc_determinism_treehash; do not edit.\n"
                << "#include \"common/identity.hpp\"\n\n"
                << "namespace dc_determinism {\n"
                << "const char* const kSourceTreeSha256 = \"" << digest << "\";\n"
                << "}  // namespace dc_determinism\n";
            if (!out) {
                std::fprintf(stderr, "cannot write %s\n", emit.c_str());
                return 1;
            }
        }
    } catch (const std::exception& error) {
        std::fprintf(stderr, "error: %s\n", error.what());
        return 1;
    }
    return 0;
}
